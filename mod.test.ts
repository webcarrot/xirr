// Numeric cases from LibreOffice's Sheet2 XIRR fixture, pinned to this revision:
// https://github.com/LibreOffice/core/blob/6b2c10e7ca30a638afaf1d7fb5483d9e5fb06b0d/sc/qa/unit/data/functions/financial/fods/xirr.fods
const flows = (entries: ReadonlyArray<readonly [string, number]>) =>
  entries.map(([date, amount]) => ({ date: new Date(date), amount }));

function assertRate(actual: number, expected: number) {
  assert.ok(
    Math.abs(actual - expected) < 1e-9,
    `expected ${expected}, got ${actual}`,
  );
}

