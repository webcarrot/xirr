test("LibreOffice A30: all positive values produce an error", () => {
  // The spreadsheet uses a date serial as the last amount.
  assert.throws(
    () =>
      xirr(
        flows([
          ["2016-01-01", 10],
          ["2016-03-01", 20],
          ["2017-01-01", 42736],
        ]),
      ),
    RangeError,
  );
});

test("retries with a scanned guess when the initial guess fails", () => {
  const entries = [
    ["2021-01-01", -1000],
    ["2022-01-01", 500],
  ] as const;
  assertRate(xirr(flows(entries)), -0.5);
  assertRate(xirr(flows(entries), -0.4), -0.5);
});

test("stops scanning when no rate can solve the cash flows", () => {
  const entries = [
    ["2021-01-01", -1000],
    ["2021-01-01", 500],
  ] as const;
  assert.throws(
    () => xirr(flows(entries), 0.1, 1e-10, 10),
    /XIRR calculation failed/,
  );
});
